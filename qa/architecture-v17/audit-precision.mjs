import fs from 'node:fs';import assert from 'node:assert/strict';
const pub='public/assets/architecture-v17/v13.glb',b=fs.readFileSync(pub),j=JSON.parse(b.subarray(20,20+b.readUInt32LE(12)));
const filters=j.bufferViews.map(v=>v.extensions?.EXT_meshopt_compression).filter(Boolean);
assert.ok(filters.length>0);assert.ok(filters.every(e=>!e.filter||e.filter==='NONE'),'Lossy Meshopt attribute filter reintroduced');
const d=JSON.parse(fs.readFileSync('qa/architecture-v17/web-surface-diagnosis.json'));
const steps=d.rows.filter(r=>Math.abs(r.x-6.15)<.01&&r.y<24.8);
assert.equal(steps.length,20);
assert.ok(steps.every(r=>r.material.includes('marble')),'Step tops must keep the source marble');
const maxHeightError=Math.max(...steps.map(r=>Math.abs(r.height-4.2)));
assert.ok(maxHeightError<0.000002,'Step heights lost source float precision');
assert.equal(d.duplicates.length,0,'Competing top surfaces at junction');
const glass=j.materials.find(m=>m.name.includes('optical low iron laminated glass'));
assert.ok(glass?.extensions?.KHR_materials_transmission?.transmissionFactor>.9,'Glass stair transmission missing');
const report={losslessBufferViews:filters.length,marbleTreadSamples:steps.length,maxHeightErrorMetres:maxHeightError,competingSurfaceSamples:d.duplicates.length,glassMaterial:glass.name};
fs.writeFileSync('qa/architecture-v17/precision-audit.json',JSON.stringify(report,null,2));console.log(report);

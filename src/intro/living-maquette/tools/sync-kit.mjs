/**
 * Regenerate the modules that are copied or derived from the production kit.
 *   node tools/sync-kit.mjs <path-to-extracted-kit>
 * - src/config/copy-deck.mjs      verbatim copy of 01_ui_package/handoff/copy_deck.json
 * - src/config/study-catalog.mjs  verbatim copy of 01_ui_package/handoff/study_catalog.json
 * - src/config/timeline-plan.mjs  verbatim adaptable_80_second_plan from ux_specification.json
 * - src/config/heading-lines.mjs  headline line breaks as drawn in 01_ui_package/screens/svg
 * - src/kit/*.mjs                 verbatim controller, integration example and scene adapter
 * tests/copy.test.mjs checks that the generated modules still equal the kit JSON.
 */
import { copyFileSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const kit = resolve(process.argv[2] ?? '');
if (!process.argv[2]) {
  console.error('usage: node tools/sync-kit.mjs <path-to-extracted-kit>');
  process.exit(1);
}
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const read = (path) => JSON.parse(readFileSync(join(kit, path), 'utf8'));
const emit = (target, name, value, source) => {
  const banner = `// Generated by tools/sync-kit.mjs from ${source}. Do not edit by hand.\n`;
  writeFileSync(join(root, target), `${banner}export const ${name} = Object.freeze(${JSON.stringify(value, null, 2)});\n`);
  console.log('wrote', target);
};

emit('src/config/copy-deck.mjs', 'COPY_DECK', read('01_ui_package/handoff/copy_deck.json'), '01_ui_package/handoff/copy_deck.json');
emit('src/config/study-catalog.mjs', 'STUDY_CATALOG', read('01_ui_package/handoff/study_catalog.json'), '01_ui_package/handoff/study_catalog.json');
emit('src/config/timeline-plan.mjs', 'TIMELINE_PLAN', read('01_ui_package/handoff/ux_specification.json').adaptable_80_second_plan,
  '01_ui_package/handoff/ux_specification.json (adaptable_80_second_plan)');

// Headline line breaks, read from the approved editable screens. Desktop
// headlines are the 68 px serif lines at x = 52; mobile ones the 37-38 px
// lines at x = 24. The interface uses them as wrapping hints only.
{
  const decode = (text) => text.replace(/<[^>]+>/g, '').replace(/&amp;/g, '&').replace(/&#39;|&apos;/g, "'")
    .replace(/&quot;/g, '"').replace(/&lt;/g, '<').replace(/&gt;/g, '>').replace(/\s+/g, ' ').trim();
  const lines = { desktop: {}, stacked: {} };
  for (const screen of read('01_ui_package/handoff/screen_index.json')) {
    if (screen.kind !== 'desktop' && screen.kind !== 'mobile') continue;
    const svg = readFileSync(join(kit, '01_ui_package', screen.svg), 'utf8');
    const wantedX = screen.kind === 'desktop' ? 52 : 24;
    const minSize = screen.kind === 'desktop' ? 60 : 37;
    const found = [];
    for (const match of svg.matchAll(/<text\b([^>]*)>([\s\S]*?)<\/text>/g)) {
      const attribute = (name) => Number((new RegExp(`\\b${name}="([-\\d.]+)"`).exec(match[1]) ?? [])[1]);
      if (attribute('x') === wantedX && attribute('font-size') >= minSize && attribute('y') < 420) {
        found.push({ y: attribute('y'), text: decode(match[2]) });
      }
    }
    if (!found.length) continue;
    found.sort((a, b) => a.y - b.y);
    const key = found.map((line) => line.text).join(' ');
    lines[screen.kind === 'desktop' ? 'desktop' : 'stacked'][key] = found.map((line) => line.text);
  }
  emit('src/config/heading-lines.mjs', 'HEADING_LINES', lines, '01_ui_package/screens/svg (headline <text> lines)');
}

for (const [from, to] of [
  ['01_ui_package/components/loader-controller.mjs', 'src/kit/loader-controller.mjs'],
  ['01_ui_package/components/loader-integration-example.mjs', 'src/kit/loader-integration-example.mjs'],
  ['05_components/maquette-scene-adapter.mjs', 'src/kit/maquette-scene-adapter.mjs'],
]) {
  copyFileSync(join(kit, from), join(root, to));
  console.log('copied', to);
}
